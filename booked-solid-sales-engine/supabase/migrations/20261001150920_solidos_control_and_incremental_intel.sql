create schema if not exists solidos_control;

create table if not exists solidos_control.settings (
  id boolean primary key default true check (id),
  system_name text not null default 'SolidOS',
  mode text not null default 'CANARY',
  planner_interval_minutes integer not null default 5 check (planner_interval_minutes between 1 and 60),
  planner_target_discoveries integer not null default 3 check (planner_target_discoveries between 1 and 20),
  planner_max_discoveries integer not null default 6 check (planner_max_discoveries between 1 and 50),
  due_backlog_soft_limit integer not null default 30 check (due_backlog_soft_limit >= 1),
  intel_dirty_batch_size integer not null default 50 check (intel_dirty_batch_size between 1 and 500),
  source_error_open_threshold integer not null default 4 check (source_error_open_threshold between 2 and 20),
  updated_at timestamptz not null default now()
);
insert into solidos_control.settings(id) values(true) on conflict(id) do nothing;

create table if not exists solidos_control.dirty_companies (
  company_id uuid primary key references booked_solid.companies(id) on delete cascade,
  reason text not null,
  priority numeric not null default 50,
  first_dirty_at timestamptz not null default now(),
  last_dirty_at timestamptz not null default now(),
  attempts integer not null default 0,
  last_error text,
  locked_at timestamptz,
  updated_at timestamptz not null default now()
);
create index if not exists dirty_companies_pick_idx
  on solidos_control.dirty_companies(priority desc,last_dirty_at,company_id);

create table if not exists solidos_control.health_events (
  id bigint generated by default as identity primary key,
  component text not null,
  severity text not null check (severity in ('INFO','WARN','ERROR')),
  event_type text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists health_events_created_idx on solidos_control.health_events(created_at desc);

create or replace function solidos_control.mark_company_dirty(
  p_company_id uuid,p_reason text,p_priority numeric default 50
) returns void
language plpgsql
security invoker
set search_path=''
as $function$
begin
  if p_company_id is null then return; end if;
  insert into solidos_control.dirty_companies(company_id,reason,priority)
  values(p_company_id,coalesce(nullif(p_reason,''),'core_change'),coalesce(p_priority,50))
  on conflict(company_id) do update set
    reason=excluded.reason,
    priority=greatest(solidos_control.dirty_companies.priority,excluded.priority),
    last_dirty_at=now(),updated_at=now();
end
$function$;

create or replace function solidos_control.core_change_dirty_trigger()
returns trigger
language plpgsql
security invoker
set search_path=''
as $function$
declare v_company uuid;
begin
  if tg_table_name='companies' then v_company:=new.id; else v_company:=new.company_id; end if;
  perform solidos_control.mark_company_dirty(v_company,tg_table_name||':'||lower(tg_op),
    case when tg_table_name in ('leads','evidence') then 80 else 60 end);
  return new;
end
$function$;

drop trigger if exists solidos_dirty_companies on booked_solid.companies;
